// ---------- snapshot ---------------------------------------------------------
function buildSnapshot(overrides = {}) {
  const snap = { baselineCommit: "daybreak-pr1@31a7e79", scenarios: {} };
  for (const [name, answers] of Object.entries(SCENARIOS)) {
    const en = runScores(answers, "en", overrides.calcSrc);
    const es = runScores(answers, "es", overrides.calcSrc);
    if (JSON.stringify(en.scores) !== JSON.stringify(es.scores)) {
      snap.scenarios[name] = { LANGUAGE_DIVERGENCE_IN_SCORES: true };
      continue;
    }
    const profileEn = runProfile(answers, "en", overrides.profileSrc);
    const profileEs = runProfile(answers, "es", overrides.profileSrc);
    snap.scenarios[name] = {
      answers,
      firmnessResolved: runFirmness(answers),
      scores: en.scores,
      matchReasons: { en: en.matchReasons, es: es.matchReasons },
      results: runResults(answers, "en", overrides),
      accessories: {
        en: runAccessories(answers, "en", overrides),
        es: runAccessories(answers, "es", overrides)
      },
      profile: {
        trialFocus: profileEn.trialFocus,
        profileName: profileEn.profileName,
        profileSubtitleByLang: profileEn.profileSubtitleByLang,
        profileBriefByLang: profileEn.profileBriefByLang,
        trialFocusLangStable:
          JSON.stringify(profileEn.trialFocus) === JSON.stringify(profileEs.trialFocus)
      }
    };
  }
  return snap;
}

// Deep structural diff with path reporting — the failure names exactly which
// scenario, surface and field moved.
function diffPaths(a, b, path = "", out = []) {
  if (out.length >= 40) return out;
  if (a === b) return out;
  const ta = Object.prototype.toString.call(a), tb = Object.prototype.toString.call(b);
  if (ta !== tb) { out.push(`${path}: ${JSON.stringify(a)} != ${JSON.stringify(b)}`); return out; }
  if (Array.isArray(a)) {
    if (a.length !== b.length) out.push(`${path}.length: ${a.length} != ${b.length}`);
    const n = Math.min(a.length, b.length);
    for (let i = 0; i < n; i++) diffPaths(a[i], b[i], `${path}[${i}]`, out);
    return out;
  }
  if (a && typeof a === "object") {
    const keys = new Set([...Object.keys(a), ...Object.keys(b)]);
    for (const k of keys) diffPaths(a[k], b[k], path ? `${path}.${k}` : k, out);
    return out;
  }
  out.push(`${path}: ${JSON.stringify(a)} != ${JSON.stringify(b)}`);
  return out;
}

