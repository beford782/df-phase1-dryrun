//
// docs/rebuild-roadmap.md, "Standing Phase 1 constraints": capture a fixture
// of fixed answer sets -> (top pick, tier assignment, ordered result list,
// computed firmness) at the Phase 1 baseline commit, and assert it unchanged
// by every Phase 1 PR alongside tests/scoring_isolation_check.mjs. This suite
// is that gate, built per the owner directive of 2026-08-12 (the open-decisions
// register entry "Phase 1 scoring-fixture exit gate" was Blake's to approve,
// and he did). It makes Invariant 2 — "nothing in Phase 1 changes what the
// engine computes" — executable rather than aspirational.
//
// WHAT IS PINNED, per scenario, from the REAL extracted engine (nothing here
// reimplements a calculation; every value is produced by executing source
// extracted verbatim from index.html):
//   - calculateScores(): the full per-mattress score map (asserted identical
//     EN vs ES, pinned once) and the per-mattress matchReasons per language;
//   - the resolved firmness input (the engine's own resolution line, executed:
//     answers.firmness if present, else the quiz slider default) and the
//     profile screen's computed feel classification (Plush/Medium/Firm word);
//   - window.showResults() derivation: per-tier ordered results with id,
//     score, pct and meetsMatchThreshold — which pins tier membership,
//     within-tier ordering, the >=60%-of-tier-max qualification, the cap of 3
//     and the back-fill to two — plus analytics.topPick and allMatches;
//   - the accessory engine: scoreAccessoriesFromAnswers() full ordered list
//     (id, score, matched, per-language reasons) and getSleepSystemViewModel()
//     step groups (support / adjustability / pillow / protection, each through
//     the same qualification, the support sub-type re-sort) plus
//     analytics.recommendedAccessories;
//   - showProfileScreen() engine state: analytics.trialFocus (the ordered 1-3
//     Sleep Brief priorities, bilingual), profileName (the 16-type profile
//     assignment), profileSubtitleByLang and profileBriefByLang.
//
// WHAT IS DELIBERATELY NOT PINNED: presentation. Sleep Brief HTML, card
// markup, chrome strings and layout are Phase 1's to change; this suite must
// never fire on an approved visual change. Only computed recommendation state
// is held. (The Sleep Brief's rendered bytes are separately pinned against
// the 572d405 baseline by tests/consultation_priorities_check.mjs for its own
// fixtures; that pin, not this one, is the one a future approved Sleep Brief
// change regenerates.)
//
// KNOWN ENGINE DEFECTS ARE BASELINE, NOT BUGS TO FIX HERE. The scoring
// case-fold defect and the unmatched quiz-tag vocabulary (roadmap 3.1 / 3.2)
// are captured exactly as they behave today. "Correcting" them would change
// what is recommended and is a Phase 3 decision requiring Blake. If a Phase 3
// change is ever approved, THIS fixture regenerates from the pre-change
// commit of that phase with its hash moved in the same reviewed diff.
//
// THE REGENERATION RATCHET (same doctrine as the consultation-priorities
// baseline): the fixture's sha256 is pinned below, so regenerating it
// requires editing two files, one of which is this comment telling the editor
// that a regenerated pin certifies whatever the change produced. The baseline
// was generated by executing the engine at commit 85c5c10 — the Phase 1
